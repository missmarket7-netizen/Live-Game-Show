let pi = 0;
const files = fs.readdirSync(dir).filter((f) => /^db\d+\.json$/.test(f)).sort();
for (const f of files) {
  const p = path.join(dir, f);
  let data = JSON.parse(fs.readFileSync(p, 'utf8'));
  let replaced = 0;
  data = data.map((q) => {
    const cat = String(q.category || '').trim();
    if (cat.indexOf('سينما') !== -1) {
      const s = pool[pi % pool.length]; pi += 1; replaced += 1;
      return { category: 'سرعة', difficulty: String(q.difficulty || 'متوسط').trim(), question: s.q, options: [], correctIndex: null, explanation: s.a };
    }
    return {
      category: cat,
      difficulty: String(q.difficulty || 'متوسط').trim(),
      question: String(q.question || '').trim(),
      options: (Array.isArray(q.options) ? q.options : []).map((o) => String(o).trim()),
      correctIndex: q.correctIndex,
      explanation: String(q.explanation || '').trim()
    };
  });
  fs.writeFileSync(p, JSON.stringify(data, null, 2), 'utf8');
  console.log(f + ' → استُبدل ' + replaced + ' سؤال سينما بسرعة');
}
